async def test_student_reading_another_students_enrollment_is_concealed_404_and_audited(
    client_db: AsyncClient, db_session: AsyncSession
) -> None:
    scope = await seed_enrollment_scope(client_db, db_session, suffix="read-blocked")
    student_profile_id = scope["student_profile_1"]["id"]
    await upload_sample(
        client_db,
        student_profile_id=student_profile_id,
        user=scope["admin"],
        content=make_jpeg_bytes(),
    )

    response = await client_db.get(
        f"/api/v1/biometric-enrollments/{student_profile_id}",
        headers=auth_headers(scope["student_2"]),
    )
    assert response.status_code == 404

    blocked_logs = (
        (
            await db_session.execute(
                select(AuditLog).where(
                    AuditLog.actor_user_id == scope["student_2"].id,
                    AuditLog.outcome == AuditOutcome.BLOCKED,
                    AuditLog.action == "biometric_enrollment.read",
                )
            )
        )
        .scalars()
        .all()
    )
    assert len(blocked_logs) == 1


