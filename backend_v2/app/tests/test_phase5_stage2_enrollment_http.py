async def test_replace_sample_succeeds_and_retires_old_sample(
    client_db: AsyncClient, db_session: AsyncSession
) -> None:
    scope = await seed_enrollment_scope(client_db, db_session, suffix="replace-ok")
    student_profile_id = scope["student_profile_1"]["id"]

