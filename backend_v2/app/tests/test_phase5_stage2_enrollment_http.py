async def test_admin_create_sample_succeeds_and_response_is_safe_metadata_only(
    client_db: AsyncClient, db_session: AsyncSession
) -> None:
    scope = await seed_enrollment_scope(client_db, db_session, suffix="create-ok")
    response = await upload_sample(
        client_db,
        student_profile_id=scope["student_profile_1"]["id"],
        user=scope["admin"],
        content=make_jpeg_bytes(),
    )
    assert response.status_code == 201, response.text
    body = response.json()

    assert body["status"] == "active"
    assert body["processing_state"] == "pending_processing"
    assert body["content_type"] == "image/jpeg"
    assert body["width_px"] == 200
    assert len(body["sha256_hash"]) == 64
    # Never a storage key, absolute path, or temp path anywhere in the body.
    serialized = str(body)
    assert "storage_key" not in body
    assert "/tmp" not in serialized
    assert "var/biometric_data" not in serialized


async def test_create_sample_refreshes_updated_at_before_response_serialization(
    client_db: AsyncClient, db_session: AsyncSession
) -> None:
    """Real-PostgreSQL regression for the former MissingGreenlet path."""
    scope = await seed_enrollment_scope(client_db, db_session, suffix="create-refresh")

    response = await upload_sample(
        client_db,
        student_profile_id=scope["student_profile_1"]["id"],
        user=scope["admin"],
        content=make_jpeg_bytes(),
    )

    assert response.status_code == 201, response.text
    body = response.json()
    assert body["status"] == "active"
    # ``updated_at`` is generated by PostgreSQL's activation UPDATE. Before
    # the fix, extracting this field after commit attempted implicit async
    # ORM I/O and raised MissingGreenlet instead of returning an HTTP response.
    assert datetime.fromisoformat(body["updated_at"]).tzinfo is not None


