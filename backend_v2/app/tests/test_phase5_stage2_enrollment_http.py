async def test_full_deletion_lifecycle_and_idempotent_finalize(
    client_db: AsyncClient, db_session: AsyncSession
) -> None:
    scope = await seed_enrollment_scope(client_db, db_session, suffix="delete-full")
    student_profile_id = scope["student_profile_1"]["id"]
    created = await upload_sample(
        client_db,
        student_profile_id=student_profile_id,
        user=scope["admin"],
        content=make_jpeg_bytes(),
    )
    assert created.status_code == 201
    sample_id = created.json()["id"]

    delete_response = await client_db.delete(
        f"/api/v1/biometric-enrollments/{student_profile_id}", headers=auth_headers(scope["admin"])
    )
    assert delete_response.status_code == 200
    assert delete_response.json()["status"] == "deleted"

    enrollment_id = delete_response.json()["id"]
    enrollment = await db_session.get(BiometricEnrollment, enrollment_id)
    assert enrollment is not None
    assert enrollment.status is EnrollmentStatus.DELETED

    sample = await db_session.get(BiometricSample, sample_id)
    assert sample is not None
    assert sample.status is SampleStatus.DELETED
    assert sample.deleted_at is not None

    # Idempotent retry: calling finalize again is a safe no-op.
    finalize_response = await client_db.post(
        f"/api/v1/biometric-enrollments/{student_profile_id}/deletion/finalize",
        headers=auth_headers(scope["admin"]),
    )
    assert finalize_response.status_code == 200
    assert finalize_response.json()["status"] == "deleted"


